EMPLOYER_PAGES = {  # lowercase key -> (written spelling, canonical title)
    spelling.lower(): (spelling, canonical)
    for canonical, aliases in EMPLOYER_VARIANTS.items()
    for spelling in (canonical, *aliases)
}
_EMPLOYER_RES = [
    (
        re.compile(
            r"(?<![A-Za-z0-9])" + re.escape(spelling) + r"(?![A-Za-z0-9])",
            # Short all-caps names must stay acronyms: ITS must not match "its".
            0 if len(spelling) <= 4 and spelling.isupper() else re.I,
        ),
        canonical,
    )
    for _, (spelling, canonical) in sorted(EMPLOYER_PAGES.items(), key=lambda kv: -len(kv[0]))
]


def anchor_id(heading: str) -> str:
    """The id a `###` heading gets from Python-Markdown's toc slugify."""
    text = unicodedata.normalize("NFKD", heading).encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", text)


def employer_spans(text: str) -> list[tuple[int, int, str]]:
    """(start, end, canonical) of each employer mention in `text`; when spans
    overlap the longer name wins ("Cisco ThousandEyes" over "Cisco")."""
    found = []
    # A two-word speaker name is not an attribution when the surname also
    # happens to be a company ("Jaakko Rautanen"). A later, delimited mention
    # of that company still matches ("Jaakko Rautanen — Rautanen").
    speaker_name = re.match(r"^\S+\s+(\S+?)(?=$|\s*(?:—|–|-|\(|,))", text)
    for rx, canonical in _EMPLOYER_RES:
        for m in rx.finditer(text):
            if speaker_name and m.start() == speaker_name.start(1):
                continue
            found.append((m.start(), m.end(), canonical))
    found.sort(key=lambda f: (f[0], f[0] - f[1]))  # by start, longest span first
    picked, taken = [], []
    for s, e, c in found:
        if any(s < t and e > b for b, t in taken):
            continue
        taken.append((s, e))
        picked.append((s, e, c))
    return picked


def link_employers(line: str, base: str = "..") -> str:
    """Link each employer mention in `line` to its page under companies/;
    `base` is the path from the page's directory to docs/."""
    spans = employer_spans(line)
    for s, e, canonical in reversed(spans):
        line = line[:s] + f"[{line[s:e]}]({base}/companies/{file_slug(canonical)}.md)" + line[e:]
    return line


def file_slug(name: str) -> str:
    """The companies/ filename of an employer page."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def links_block(row: str, title: str) -> tuple[list[str], list[str]]:
    """A pick's plain source links and recording player (which decorate()
    puts after the title and speakers, just before "Why")."""
    links = MD_LINK.findall(row)
    if not links:
        return [f"**Links:** {row}"], []
    source_links = " ".join(
        f"[{text.strip()}]({url}){{ .pick-link }}"
        for text, url in links
    )
    out = ['<div class="pick-links" markdown>', "", source_links, "", "</div>", ""]
    player: list[str] = []
    recording = next((url for text, url in links if text.lower() == "recording"), None)
    video = youtube_id(recording) if recording else None
    if video:
        start = youtube_start(recording)
        alt = re.sub(r"[\"<>&]", "", f"Play the recording: {title}")[:160]
        player = [
            f'<div class="pick-video"><a class="pick-video__thumb" data-yt="{video}" data-start="{start}" '
            f'href="https://www.youtube.com/watch?v={video}{f"&t={start}s" if start else ""}" target="_blank" rel="noopener">'
            f'<img src="https://i.ytimg.com/vi/{video}/hqdefault.jpg" '
            f'data-hd="https://i.ytimg.com/vi/{video}/maxresdefault.jpg" alt="{alt}" loading="lazy">'
            f'<span class="pick-video__play" aria-hidden="true"></span></a></div>',
            "",
        ]
    elif recording and re.search(r"\.(?:mp4|m4v|webm|ogv|ogg)(?:[?#]|$)", recording, re.I):
        src = escape(recording, quote=True)
        label = escape(f"Recording: {title}", quote=True)
        player = [
            f'<div class="pick-video"><video class="pick-video__frame" controls playsinline preload="none" '
            f'src="{src}" aria-label="{label}">'
            f'<a href="{src}">Watch the recording</a></video></div>',
            "",
        ]
    return out, player


def media_block(row: str, title: str) -> list[str]:
    """Talk-only media tabs: recording first, then PPTX, then PDF."""
    _, video = links_block(row, title)
    # A block-level div inside a Markdown tab splits it from the following tabs.
    video_html = "\n".join(video).strip().removeprefix('<div class="pick-video">').removesuffix("</div>")
    tabs = [("Video", [video_html])] if video else []
    decks = []
    for text, url in MD_LINK.findall(row):
        if not re.fullmatch(r"Slides(?: \([^)]*\)| 2)?", text.strip(), re.I):
            continue
        extension = Path(urlsplit(url).path).suffix.lower()
        if extension in (".pptx", ".pdf"):
            decks.append((extension[1:].upper(), url))
    decks.sort(key=lambda deck: deck[0] != "PPTX")
    for i, (fmt, url) in enumerate(decks):
        src = "https://view.officeapps.live.com/op/embed.aspx?src=" + quote(url, safe="") if fmt == "PPTX" else url
        # GitHub serves PDFs as downloads with X-Frame-Options: deny, but permits CORS.
        download = fmt == "PDF" and urlsplit(url).hostname in ("media.githubusercontent.com", "raw.githubusercontent.com")
        source = f'data-pdf-src="{escape(url, quote=True)}"' if download else f'src="{escape(src, quote=True)}"'
        label = escape(f"{fmt} slides: {title}", quote=True)
        frame = (
            f'<iframe class="pick-slides__frame" {source} '
            f'title="{label}" loading="lazy" allowfullscreen></iframe>'
        )
        number = sum(1 for kind, _ in decks[:i + 1] if kind == fmt)
        tab = f"{fmt} {number}" if sum(1 for kind, _ in decks if kind == fmt) > 1 else fmt
        tabs.append((tab, [frame]))
    if not tabs:
        return []
    out = ['<div class="pick-media" markdown>', ""]
    for tab, content in tabs:
        out.extend([f'=== "{tab}"', "", *(f"    {line}" for line in "\n".join(content).strip().splitlines()), ""])
    out.extend(["</div>", ""])
    return out


# The keywords block a digest writer emits at its very end (conferences/prompt/
# base.md): a fenced json object with `post` and `talks` keys. The pipeline
# strips it before the digest is published and turns it into tags.yaml
# (propose_digest.py for bot digests, generate_tags.py --from-digest by hand).
TAGS_BLOCK = re.compile(r"(?:\A|\n)```(?:json)?[ \t]*\n(\{\s*\"post\".*?)\n```[ \t]*(?=\n|$)", re.S)


def extract_tags_block(markdown: str) -> tuple[str, str | None]:
    """(the digest without its keywords block, the block's JSON body), or
    (the digest, None) when it carries none."""
    m = TAGS_BLOCK.search(markdown)
    if not m:
        return markdown, None
    text = (markdown[: m.start()] + markdown[m.end() :]).rstrip() + "\n"
    return text, m.group(1).strip()


