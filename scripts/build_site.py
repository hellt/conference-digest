def annotate_employers(rest: str, base: str = "..") -> tuple[str, list[dict]]:
    """Link employer names in every pick's attribution, and return the pick
    records companies pages are built from.

    The attribution is the first line after the heading that is neither the
    links row nor a write-up bullet; netdev and SIGCOMM put it in the heading
    ("### Title — Speakers (Employer) — Tier"), in which case the heading is
    linkified instead — and never both, so a talk whose *title* names a company
    ("TikTok's IPv6 Journey") doesn't get linked by its title.
    """
    lines = rest.split("\n")
    tier = None
    picks: list[dict] = []
    for i, line in enumerate(lines):
        if line.startswith("## "):
            slug = tier_of(line[3:])
            tier = slug if slug in TIERS else None
        elif line.startswith("### ") and tier:
            heading = line[4:].strip()
            j = attribution_line(lines, i)
            if j < 0:  # netdev/SIGCOMM: attribution is the heading itself
                spans = employer_spans(line)
                if not spans:
                    continue
                lines[i] = link_employers(line, base)
                m = HEADED.match(line)
                picks.append({
                    "tier": tier,
                    "title": m.group(1) if m else heading,
                    "speakers": plain(m.group(2)) if m else plain(heading),
                    "anchor": anchor_id(heading),
                    "employers": sorted({c for _, _, c in spans}),
                })
            else:
                attributed = lines[j]
                spans = employer_spans(attributed)
                if not spans:
                    continue
                lines[j] = link_employers(attributed, base)
                speakers = AUTHORS.sub("", attributed.strip()).strip("*")
                picks.append({
                    "tier": tier,
                    "title": heading,
                    "speakers": plain(speakers),
                    "anchor": anchor_id(heading),
                    "employers": sorted({c for _, _, c in spans}),
                })
    return "\n".join(lines), picks


def front_matter(fields: dict) -> str:
    """YAML front matter, one JSON value per key (JSON is valid YAML)."""
    return "---\n" + "".join(f"{k}: {json.dumps(v, ensure_ascii=False)}\n" for k, v in fields.items()) + "---\n\n"


def conference_parts(name: str) -> tuple[str, str]:
    """("AutoCon 5", "Munich") from "AutoCon 5 (Munich)". A parenthetical that
    isn't a place ("22nd USENIX Symposium on ...") is dropped."""
    m = re.fullmatch(r"(.*?)\s*\(([^()]*)\)", name.strip())
    if not m:
        return name.strip(), ""
    inner = m.group(2).strip()
    place = inner if not re.search(r"\d", inner) and len(inner.split()) <= 3 else ""
    return m.group(1), place


def date_span(start: date | None, end: date | None) -> str:
    """"19–21 October 2026", "30 May – 2 June 2026"."""
    if not end:
        return ""
    if not start or start >= end:
        return f"{end.day} {end:%B} {end.year}"
    if (start.year, start.month) == (end.year, end.month):
        return f"{start.day}–{end.day} {end:%B} {end.year}"
    if start.year == end.year:
        return f"{start.day} {start:%B} – {end.day} {end:%B} {end.year}"
    return f"{start.day} {start:%B} {start.year} – {end.day} {end:%B} {end.year}"


# A tier tag closing an attribution line: "— **Core**", "*Core.*".
TIER_TAIL = re.compile(r"\s*(?:[—–-]\s*)?\*{0,2}(?:Core|Adjacent|Wildcard)\b[.*]*\s*$")
LABEL_LEAD = re.compile(r"^\s*(?:[-*+]\s+)?\*\*(?:Why|What|How)\b[^*]*\*\*:?\s*")


def pick_sections(rest: str) -> list[dict]:
    """Each pick in `rest` (the digest from its first ##), in order: tier,
    heading and the lines under the heading. Same rules as decorate(), so the
    n-th section here is the n-th pick card there."""
    picks: list[dict] = []
    tier, in_fence, current = None, False, None
    for line in rest.split("\n"):
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("## "):
            slug = tier_of(line[3:].strip())
            tier = slug if slug in TIERS else None
            current = None
            continue
        if not in_fence and line.startswith("### "):
            current = {"tier": tier, "heading": line[4:].strip(), "lines": []} if tier else None
            if current:
                picks.append(current)
            continue
        if current is not None:
            current["lines"].append(line)
    return picks


def summary(text: str, limit: int = 240) -> str:
    """Plain text cut at the last sentence that fits, else at a word."""
    text = plain(text, 10_000)
    if len(text) <= limit:
        return text
    cut = text[:limit].rfind(". ")
    return text[: cut + 1] if cut >= limit // 3 else plain(text, limit)


def tidy_presenter(text: str) -> str:
    """Drop a sentence-final period ("…(Tsinghua University).") but keep one
    that ends an abbreviation ("Inc.", "Ed.")."""
    text = plain(text, 240)
    last = text.rsplit(" ", 1)[-1]
    return text[:-1] if text.endswith(".") and (last.endswith(").") or len(last) > 4) else text


def first_writeup(lines: list[str]) -> str:
    """The pick's first Why/What/How paragraph as plain text, label dropped."""
    for i, line in enumerate(lines):
        if WRITEUP_RE.match(line):
            text = [LABEL_LEAD.sub("", line)]
            for more in lines[i + 1:]:
                if not more.strip() or re.match(r"\s*(?:[-*+]\s|\*\*)", more):
                    break
                text.append(more.strip())
            return " ".join(text)
    return ""


def render_talks(key: str, name: str, digest_title: str, started: date | None, ended: date | None,
                 sections: list[dict], talk_tags: dict[str, list[str]] | None = None,
                 source: str = "") -> tuple[list[tuple[str, str]], list[str]]:
    """One page per pick, as (path under docs/, page text), and each
    page's href from docs/posts/, in pick order. The pick's text is rendered
    as on the digest; the page adds a facts strip and the card front matter."""
    conference, place = conference_parts(name)
    dates = date_span(started, ended)
    pages: list[tuple[str, str]] = []
    hrefs: list[str] = []
    used: set[str] = set()
    for pick in sections:
        heading, tier, lines = pick["heading"], pick["tier"], list(pick["lines"])
        headed = HEADED.match(f"### {heading}")
        title = headed.group(1) if headed else heading
        if headed:   # netdev/SIGCOMM: speakers ride in the heading; give them their own line
            presenter = plain(headed.group(2), 400)
            at = next((k + 1 for k, l in enumerate(lines) if LINKS_ROW.match(l)), 0)
            lines[at:at] = ["", f"*{presenter}*", ""]
        else:
            j = attribution_line([f"### {heading}", *lines], 0)
            presenter = plain(TIER_TAIL.sub("", AUTHORS.sub("", lines[j - 1].strip())), 400) if j > 0 else ""
        slug = anchor_id(plain(title, 1000))[:72].strip("-") or "talk"
        stem, n = slug, 2
        while slug in used:
            slug, n = f"{stem}-{n}", n + 1
        used.add(slug)

        annotated, _ = annotate_employers(f"## {tier}\n\n### {title}\n" + "\n".join(lines), base="..")
        body = decorate(annotated, media_tabs=True).split("\n")
        body = [l for l in body if not l.startswith("## ")]
        body.pop(next(k for k, l in enumerate(body) if l.startswith("### ")))

        facts = [
            f"[{digest_title} digest](../posts/{key}.md#{anchor_id(heading)})",
            f"[Program]({source})" if source.startswith("http") else "",
            f"{tier.title()} pick",
            " · ".join(x for x in (place, dates) if x),
        ]
        facts_html = "\n".join(f'<span class="digest-fact" markdown>{f}</span>' for f in facts if f)
        front = {
            "title": plain(title, 1000),
            "description": summary(first_writeup(lines)) or f"A {tier} pick from the {digest_title} digest.",
        }
        tags = (talk_tags or {}).get(heading)
        if tags:
            front["tags"] = tags
        front["card"] = {
            "kind": "talk",
            "conference": conference,
            "when": " · ".join(x for x in (place, dates, f"{tier.title()} pick") if x),
            "title": plain(title, 1000),
            "presenter": tidy_presenter(presenter),
        }
        page = (
            front_matter(front)
            + f"# {title}\n\n"
            + f'<div class="digest-facts" markdown>\n{facts_html}\n</div>\n\n'
            + "\n".join(body).strip()
            + "\n"
        )
        pages.append((f"{key}/{slug}.md", page))
        hrefs.append(f"../{key}/{slug}.md")
    return pages, hrefs


def render_post(key: str, entry: dict, meta: dict, body: str,
                tags: dict | None = None) -> tuple[str, dict, list[dict], list[tuple[str, str]]]:
    h1, intro, rest = split_body(nest_lists(body))
    if re.match(r"^\d+ picks\b", intro):
        intro = intro.partition("\n\n")[2]
    name = entry.get("name") or meta.get("conference") or key
    description = str(entry.get("description", "")).strip()
    if not description:
        raise ValueError(f"{key}: add a short description to its registry entry")
    title = clean_title(h1, name)
    written_by = str(meta.get("written_by", "")).strip()
    bot = written_by.lower().startswith("tofarev")
    # Posts are dated by the conference, not by when the digest was written,
    # so the blog lists the most recent conference first.
    published = as_date(entry.get("end_date")) or as_date(meta.get("generated")) or date.today()
    started = as_date(entry.get("start_date"))
    ended = as_date(entry.get("end_date"))
    dates = f"{human(started)} – {human(ended)}" if started and ended else human(ended) if ended else ""
    # The human-facing page; a fetcher's source_url can be an API endpoint.
    source = entry.get("manual_fallback_url") or meta.get("source_url") or entry.get("program_url") or ""
    sections = pick_sections(rest)
    tags = tags or {}
    talks, talk_links = render_talks(key, name, title, started, ended, sections, tags.get("talks"), source)
    decorated, picks = annotate_employers(rest)
    decorated = decorate(decorated, talk_links)

    counts = {t: sum(1 for s in sections if s["tier"] == t) for t in TIERS}
    total = sum(counts.values())
    front = {
        "date": published.isoformat(),
        "slug": key,
        "title": title,
        "description": summary(description, 180),
        "conference_dates": list_date_span(started, ended),
        "media_pending": not has_media(body),
        "card": {
            "kind": "digest",
            "conference": "Conference digest",
            "when": " · ".join(x for x in (conference_parts(name)[1], date_span(started, ended)) if x),
            "title": title,
            "presenter": f"{total} pick{'' if total == 1 else 's'}: "
                         + ", ".join(f"{n} {t}" for t, n in counts.items() if n),
        },
    }
    if entry.get("location"):
        front["location"] = entry["location"]
    if bot:
        front["authors"] = ["tofarev"]
    post_tags = tags.get("post")
    if post_tags:
        front["tags"] = post_tags
    facts = [
        dates,
        f"[Program]({source})" if source.startswith("http") else "",
    ]
    facts_html = "\n".join(f'<span class="digest-fact" markdown>{f}</span>' for f in facts if f)
    if bot:
        about = (
            "ToFaRev picked and wrote this digest "
            "on Nebius Token Factory, from the conference's published program. A person reviewed it in a pull request "
            "before it was published. Write-ups marked \"from abstract only\" had no fuller source to read."
        )
    else:
        about = "This digest was produced by running the repository's digest prompt by hand, from the conference's published program."
    footer = (
        f'!!! info "About this digest"\n\n'
        f"    {about} Source: [`digests/{key}.md`]({REPO}/blob/main/digests/{key}.md)"
        + (f" · prompt: [`prompts/{key}.md`]({REPO}/blob/main/prompts/{key}.md)" if (PROMPTS / f"{key}.md").exists() else "")
        + "\n"
    )
    page = (
        front_matter(front)
        + f"# {title}\n\n{intro}\n\n<!-- more -->\n\n"
        + f'<div class="digest-facts" markdown>\n{facts_html}\n</div>\n\n'
        # Search finds a digest by its name and intro only; each pick is
        # indexed once, from its talk page, so results lead to talk pages.
        + '<div class="digest-body" data-search-exclude markdown>\n\n'
        + exclude_from_search(decorated)
        + "\n"
        + footer
        + "\n</div>\n"
    )
    return page, {"key": key, "title": title, "date": published, "bot": bot}, picks, talks


STATUS = {
    "local_required": ":material-laptop: Needs a local fetch",
    "manual": ":material-content-paste: Needs a manual paste",
    "waiting": ":material-timer-sand: Waiting for the program",
    "stalled": ":material-alert-outline: Fetcher stalled",
    "pending": ":material-timer-sand: Queued",
}


def render_tracker(registry: dict[str, dict], posts: dict[str, dict]) -> str:
    state = json.loads(STATE.read_text(encoding="utf-8")) if STATE.exists() else {}
    today = date.today()
    rows = []
    entries = sorted(registry.values(), key=lambda e: as_date(e.get("end_date")) or date.min, reverse=True)
    for e in entries:
        key = e["key"]
        ended = as_date(e.get("end_date"))
        url = e.get("manual_fallback_url") or e.get("program_url") or ""
        name = e["name"].replace("|", "\\|")
        if key in posts:
            status = f"[:material-check-circle: Read the digest](posts/{key}.md)"
        elif ended and ended > today:
            status = ":material-calendar-clock: Upcoming"
        elif (PROMPTS / f"{key}.md").exists():
            status = ":material-robot-outline: Digest in progress"
        else:
            status = STATUS.get(state.get(key, {}).get("status", "pending"), STATUS["pending"])
        conference = f"[{name}]({url})" if url.startswith("http") else name
        rows.append(f"| {conference} | {ended or '?'} | {status} |")
    return (
        "---\ntitle: Conferences\nhide:\n  - toc\n---\n\n"
        "# Conferences\n\n"
        "Every conference edition the pipeline tracks, newest first. A digest is written after the "
        "event ends and its program is published. [How it works](how-it-works.md) explains each status.\n\n"
        '<div class="conf-filter">\n'
        '<input id="conf-search" type="search" autocomplete="off" '
        'placeholder="Filter by conference name" aria-label="Filter conferences by name">\n'
        "</div>\n\n"
        "| Conference | Ended | Status |\n|---|---|---|\n" + "\n".join(rows) + "\n"
    )


def render_companies(companies: dict[str, list[dict]], posts: dict[str, dict]) -> None:
    """One page per employer — every picked talk with one of its speakers,
    grouped by digest, newest first — plus the Companies index."""
    if COMPANIES.exists():
        shutil.rmtree(COMPANIES)
    COMPANIES.mkdir(parents=True)
    plural = lambda n: "" if n == 1 else "s"
    for name in sorted(companies, key=str.lower):
        picks = companies[name]
        digests: dict[str, list[dict]] = {}
        for p in sorted(picks, key=lambda p: posts[p["key"]]["date"], reverse=True):
            digests.setdefault(p["key"], []).append(p)
        order = sorted(digests, key=lambda k: posts[k]["date"], reverse=True)
        summary = f"{len(picks)} picked talk{plural(len(picks))} across {len(digests)} digest{plural(len(digests))}"
        page = [
            front_matter({
                "title": name,
                "description": f"Every picked talk across the conference digests with a speaker from {name}.",
                "card": {"kind": "employer", "conference": "Company", "title": name, "presenter": summary},
            }).rstrip("\n"),
            "",
            f"# {name}",
            "",
            f"{summary} with a speaker from {name}, newest first.",
            "",
        ]
        for k in order:
            page += [f"## {posts[k]['title']}", ""]
            for p in digests[k]:
                page.append(f"- [{p['title']}](../posts/{k}.md#{p['anchor']}) · *{p['tier'].title()}* — {p['speakers']}")
            page.append("")
        (COMPANIES / f"{file_slug(name)}.md").write_text("\n".join(page) + "\n", encoding="utf-8")
    entries = "\n".join(
        "| [{}]({}.md) | {} |".format(
            name.replace("|", "\\|"), file_slug(name), len(companies[name])
        )
        for name in sorted(companies, key=str.lower)
    )
    index = (
        "---\n"
        "title: Companies\n"
        "description: Every company behind the picked talks, with all their talks across the digests.\n"
        "hide:\n"
        "  - toc\n"
        "---\n\n"
        "# Companies\n\n"
        "Each digest names the people behind its picks and who they speak for. These pages collect "
        "the picked talks by company, across every conference, newest first; company names in a "
        "digest link here.\n\n"
        '<div class="conf-filter">\n'
        '<input id="company-search" type="search" autocomplete="off" '
        'placeholder="Filter by employer name" aria-label="Filter employers by name">\n'
        "</div>\n\n"
        "| Employer | Talks |\n|---|---|\n" + entries + "\n"
    )
    (COMPANIES / "index.md").write_text(index, encoding="utf-8")


def main() -> int:
    registry = load_registry()
    tag_index = load_tags()
    if POSTS.exists():
        shutil.rmtree(POSTS)
    POSTS.mkdir(parents=True)
    for old in DOCS.iterdir():   # last run's talk pages, including digests since removed
        if (old / ".gitignore").is_file() and (old / ".gitignore").read_text(encoding="utf-8") == TALKS_MARKER:
            shutil.rmtree(old)
    posts: dict[str, dict] = {}
    companies: dict[str, list[dict]] = {}
    talk_count = 0
    for path in sorted(DIGESTS.glob("*.md")):
        key = path.stem
        meta, body = read_digest(path)
        page, info, picks, talks = render_post(key, registry.get(key, {}), meta, body, tag_index.get(key))
        (POSTS / f"{key}.md").write_text(page, encoding="utf-8")
        if talks:
            folder = DOCS / key
            if folder.exists():   # never write into a hand-made docs/ folder
                raise SystemExit(f"docs/{key}/ exists and is not generated; it would collide with {key}'s talk pages")
            folder.mkdir()
            (folder / ".gitignore").write_text(TALKS_MARKER, encoding="utf-8")
            for rel, text in talks:
                (DOCS / rel).write_text(text, encoding="utf-8")
        talk_count += len(talks)
        posts[key] = info
        for p in picks:
            p["key"] = key
            for employer in p["employers"]:
                companies.setdefault(employer, []).append(p)
    render_companies(companies, posts)
    TRACKER.write_text(render_tracker(registry, posts), encoding="utf-8")
    print(f"rendered {len(posts)} digest post(s), {talk_count} talk page(s), {len(companies)} employer page(s) "
          f"and the tracker of {len(registry)} edition(s)"
          + (f"; {sum(1 for t in tag_index.values() if t.get('post'))} digest(s) carry search tags"
             if tag_index else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
