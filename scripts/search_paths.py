#!/usr/bin/env python3
"""Rewrite search-result breadcrumbs after `zensical build`.

Zensical's search index gives a top-level page section a `path` of exactly one
entry - the page's own H1 - and the search UI shows that path under the result
title. For a talk page the H1 *is* the title, so the second line of every talk
result just repeats the first. This script rewrites `site/search.json`:

  - talk pages   (docs/<key>/<slug>/): path := [conference, date-span]
  - digest posts (docs/posts/<key>/) : path := ["Conference digest", date-span]

Both come from the same registry metadata `build_site.py` renders those pages
from, so the breadcrumb says where a talk is from and when - for a talk page
its H1 *is* the talk title, and a digest post's H1 is the conference name,
so in both cases the natural path would just repeat the title. The `path`
field is indexed with weight 2, so this also makes talks findable by
conference name or year. Company and archive pages keep their natural
breadcrumbs and are left alone.

Run after the build (the Makefile `site` target does): the search index is
generated by Zensical's compiled search plugin, so this is the one hook that
can shape it. `make serve-site` does not run it; live preview keeps the raw
breadcrumbs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_site import (  # noqa: E402
    DIGESTS,
    as_date,
    conference_parts,
    date_span,
    load_registry,
    read_digest,
)


def conference_breadcrumbs() -> dict[str, dict[str, list[str]]]:
    """Per digest key, the talk and post breadcrumbs, mirroring render_talks
    and render_post: `name` prefers the registry entry, dates come from the
    registry's start/end_date. A talk says which conference it is from; a
    digest post's title is the conference name itself, so its breadcrumb says
    what kind of page it is - "Conference digest", the eyebrow its card uses
    - and when the conference took place."""
    registry = load_registry()
    crumbs: dict[str, dict[str, list[str]]] = {}
    for digest in sorted(DIGESTS.glob("*.md")):
        key = digest.stem
        entry = registry.get(key, {})
        meta, _ = read_digest(digest)
        name = entry.get("name") or meta.get("conference") or key
        conference = conference_parts(name)[0]
        dates = date_span(as_date(entry.get("start_date")), as_date(entry.get("end_date")))
        crumbs[key] = {
            "talk": [c for c in (conference, dates) if c] or [key],
            "post": [c for c in ("Conference digest", dates) if c],
        }
    return crumbs


def main() -> int:
    site = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("site")
    index = site / "search.json"
    if not index.is_file():
        raise SystemExit(f"{index} not found; run `zensical build` first")
    data = json.loads(index.read_text(encoding="utf-8"))
    crumbs = conference_breadcrumbs()

    talks = posts = 0
    for item in data["items"]:
        location = item["location"]
        if "#" in location:   # a section anchor inside a page, not the page
            continue
        parts = location.strip("/").split("/")
        if len(parts) == 1 and parts[0] in crumbs:            # the digest post
            item["path"] = crumbs[parts[0]]["post"]
            posts += 1
        elif len(parts) == 2 and parts[0] in crumbs:          # a talk page
            item["path"] = crumbs[parts[0]]["talk"]
            talks += 1

    index.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"search breadcrumbs: {talks} talk page(s) and {posts} digest post(s) "
          "now show their conference and date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
